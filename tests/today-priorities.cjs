const assert = require('node:assert/strict');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
  await context.addInitScript(() => { sessionStorage.setItem('alusathi-demo', 'true'); sessionStorage.setItem('alusathi-role', 'farmer'); });
  const page = await context.newPage();
  try {
    await page.route('https://api.open-meteo.com/**', route => route.abort());
    await page.goto('http://127.0.0.1:4176/farmer', { waitUntil: 'domcontentloaded' });
    await page.locator('.today-task').first().waitFor();
    assert.equal(await page.locator('.today-task').count(), 3);
    assert.equal(await page.locator('.today-task-toggle').count(), 3);
    assert.equal(await page.getByText('আলুসাথী AI পর্যবেক্ষণ').count(), 1);
    assert.equal(await page.getByText('আলুর ছবি বেছে নিলে এখানে ফল ও করণীয় দেখাবে।').count(), 1);
    assert.equal(await page.locator('.today-task-details:visible').count(), 0);
    assert.equal(await page.locator('.care-panel[open]').count(), 0);
    await page.locator('.today-task-toggle').first().click();
    assert.equal(await page.locator('.today-task-details').first().isVisible(), true);
    await page.locator('.today-task-toggle').nth(1).click();
    assert.equal(await page.locator('.today-task-details').first().isVisible(), false);
    assert.equal(await page.locator('.today-task-details').nth(1).isVisible(), true);
    const first = page.locator('.today-task input').first();
    await first.check();
    const ids = await page.evaluate(() => JSON.parse(localStorage.getItem('alusathi-field-actions-v1') || '[]').filter(x => x.id.startsWith('today|')).map(x => x.id));
    assert.equal(ids.length, 1);
    await page.evaluate(() => {
      const entries = JSON.parse(localStorage.getItem('alusathi-field-actions-v1') || '[]');
      const date = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Dhaka', year:'numeric', month:'2-digit', day:'2-digit' }).format(new Date());
      entries.unshift({ id:'photo-new', date, district:'Rangpur', kind:'observation', category:'photo', text:'Marked potato', advice:'observe', title:'Marks visible', image:'https://example.invalid/tracker.jpg' });
      localStorage.setItem('alusathi-field-actions-v1', JSON.stringify(entries));
      window.dispatchEvent(new Event('alusathi-field-actions-changed'));
    });
    await page.waitForFunction(() => document.querySelector('.today-task-list')?.textContent.includes('দাগযুক্ত'));
    assert.equal(await page.locator('.today-ai-insight').getByText('ছবির নোট', { exact: true }).count(), 1);
    assert.equal(await page.locator('.today-ai-insight img').count(), 0);
    assert.equal(await page.locator('.today-task input:checked').count(), 1);
    for (const box of await page.locator('.today-task input').all()) if (!await box.isChecked()) await box.check();
    assert.equal(await page.locator('.today-task input:checked').count(), 3);
    await page.reload();
    await page.locator('.today-task').first().waitFor();
    await page.waitForFunction(() => document.querySelectorAll('.today-task input:checked').length === 3, null, { timeout: 5000 });
    assert.equal(await page.evaluate(() => new Set(JSON.parse(localStorage.getItem('alusathi-field-actions-v1') || '[]').filter(x => x.id.startsWith('today|')).map(x => x.id)).size), 3);
    const completedText = await page.locator('.today-task h3').allTextContents();
    await page.goto('http://127.0.0.1:4176/farmer#diary');
    await page.locator('#diary').getByText(completedText[0], { exact: true }).first().waitFor();
    for (const text of completedText) assert.ok(await page.locator('#diary').getByText(text, { exact: true }).count());
    await page.goto('http://127.0.0.1:4176/farmer');
    await page.locator('.today-task').first().waitFor();
    await page.locator('.today-task-toggle').first().focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('.today-task-toggle').first().getAttribute('aria-expanded'), 'true');
    await page.locator('.care-auto-fertilizer > summary').click();
    const fertilizer = page.locator('.care-auto-fertilizer');
    assert.match(await fertilizer.innerText(), /১ একরে ৬৪\.৭৫–৭০\.৮২ কেজি/);
    assert.doesNotMatch(await fertilizer.innerText(), /লাগানোর তারিখ দিন|শেষ প্রয়োগ খাতায়/);
    assert.doesNotMatch(await page.locator('.today-location').innerText(), /ধরা হয়েছে/);
    assert.equal(await page.getByText('আজ কি সার দিয়েছেন?').isVisible(), true);
    await page.locator('.care-auto-spray > summary').click();
    assert.equal(await page.locator('.care-auto-spray').getByText('শুধু ছবি দেখে স্প্রে বাছাই করা যায় না।').isVisible(), true);
    await page.locator('.care-auto-spray > summary').click();
    assert.equal(await page.locator('.care-auto-spray').getByText('শুধু ছবি দেখে স্প্রে বাছাই করা যায় না।').isVisible(), false);
    await page.locator('.today-task input').first().uncheck();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('alusathi-field-actions-v1') || '[]').filter(x => x.id.startsWith('today|')).length), 2);
    await page.screenshot({ path: 'test-results/today-v2.png', fullPage: true });
    console.log('Desktop: accordion, changing inputs, three completions, refresh, undo and care panels passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
